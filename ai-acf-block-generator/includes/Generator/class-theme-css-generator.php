		$css .= ".{$bem}__arrow:hover { background: {$accent}; border-color: {$accent}; color: #001529; }\n\n";

		$css .= ".{$bem}__slider.is-single .{$bem}__nav,\n";
		$css .= ".{$bem}__slider.is-single .{$bem}__dots { display: none !important; }\n\n";

		return $css;
	}

	/**
	 * Accordion CSS.
	 *
	 * @param string $bem Component class.
	 * @param array  $t   Tokens.
	 * @return string
	 */
	private function accordion_css( $bem, $t ) {
		$css  = ".{$bem}__item { border-bottom: 1px solid #e0e0e0; }\n";
		$css .= ".{$bem}__trigger {\n";
		$css .= "  width: 100%;\n";
