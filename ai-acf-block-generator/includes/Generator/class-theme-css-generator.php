	}

	/**
	 * Collect every cell class referenced by the layout structure.
	 *
	 * @param array $spec Block spec.
	 * @return array
	 */
	private function collect_cell_classes( $spec ) {
		$cells = array();

		foreach ( $spec['layout_structure']['rows'] ?? array() as $row ) {
			foreach ( $row['columns'] ?? array() as $column ) {
				if ( ! empty( $column['cell_class'] ) ) {
					foreach ( preg_split( '/\s+/', trim( $column['cell_class'] ) ) as $class ) {
						if ( 0 === strpos( $class, 'cell-' ) ) {
							$cells[ $class ] = $class;
						}
					}
				}
			}
		}

		return array_values( $cells );
	}

	/**
	 * Whether any row defines more than one column.
	 *
	 * @param array $spec Block spec.
	 * @return bool
	 */
	private function structure_has_multiple_columns( $spec ) {
		foreach ( $spec['layout_structure']['rows'] ?? array() as $row ) {
			if ( count( $row['columns'] ?? array() ) > 1 ) {
				return true;
			}
		}

		return false;
	}

	/**
	 * Whether the spec contains a repeater field.
	 *
	 * @param array $fields Fields.
	 * @return bool
	 */
	private function has_repeater( $fields ) {
		foreach ( $fields as $field ) {
			if ( 'repeater' === ( $field['type'] ?? '' ) ) {
				return true;
			}
		}

		return false;
	}

	/**
	 * Sanitise a CSS colour value; fall back when empty/invalid.
	 *
	 * @param string $value    Raw value.
	 * @param string $fallback Fallback colour.
	 * @return string
	 */
	private function css_color( $value, $fallback ) {
		$value = trim( (string) $value );

		if ( '' === $value ) {
			return $fallback;
		}

		if ( preg_match( '/^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/', $value ) ) {
			return $value;
		}

		if ( preg_match( '/^(?:rgb|rgba|hsl|hsla)\([0-9.,%\s\/]+\)$/i', $value ) ) {
			return $value;
		}

		// Named colours / CSS keywords: allow simple word tokens only.
		if ( preg_match( '/^[a-zA-Z]+$/', $value ) ) {
			return strtolower( $value );
		}

		return $fallback;
	}

	/**
	 * Sanitise a generic CSS length/shorthand value.
	 *
	 * @param string $value    Raw value.
	 * @param string $fallback Fallback value.
	 * @return string
	 */
	private function css_value( $value, $fallback ) {
		$value = trim( (string) $value );

		if ( '' === $value ) {
			return $fallback;
		}

		// Block anything that could break out of the declaration.
		if ( preg_match( '/[;{}<>]/', $value ) ) {
			return $fallback;
		}

		return $value;
	}
